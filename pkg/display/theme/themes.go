const DefaultName = "Paper"

const Follow = "Default"

func Default() Theme {
	t, _ := ByName(DefaultName)
	return t
}

func Names() []string {
	out := make([]string, 0, len(All))
	for _, t := range All {
		out = append(out, t.Name)
	}
	return out
}

func ByName(name string) (Theme, bool) {
	for _, t := range All {
		if t.Name == name {
			return t, true
		}
	}
	return Theme{}, false
}
